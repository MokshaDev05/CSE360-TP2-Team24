package validation;

/*******
 * <p> Title: InputLimits Class. </p>
 * 
 * <p> Description: A single place that defines how long each kind of textual input is
 * allowed to be, plus the shared check that enforces those limits.</p>
 * 
 * <p> Every text field in the application passes through this check before any other
 * processing takes place.  The reason is defensive: a common way to probe an application
 * for weaknesses is to paste a very long string into each field and see whether the
 * program crashes.  A crash tells an attacker that the input is reaching code that does
 * not expect it, which is an invitation to keep digging.  Checking the length first, and
 * rejecting the input with a plain message, removes that easy signal.</p>
 * 
 * <p> Two levels of limit are used.  ABSOLUTE_MAX is a cheap ceiling applied to any input
 * before the more expensive per-field checks run, so that no recognizer ever walks a
 * multi-megabyte string.  The per-field limits are then applied according to what the
 * field means.</p>
 * 
 * <p> Copyright: Lynn Robert Carter (c) 2025.  TP1 additions by CSE 360 Team: Arush Ugal,
 * Karan Patel, Anirudh B, Pranjal Ganvir, Moksha Dev. </p>
 * 
 * @author CSE 360 TP1 Team
 * 
 * @version 1.00  2026-09-22  Initial version for Team Project Phase 1
 */
public class InputLimits {

	/** The largest input, in characters, that any field will even look at. */
	public static final int ABSOLUTE_MAX = 256;

	/** Usernames are limited to 16 characters, which matches the HW1 recognizer. */
	public static final int MAX_USERNAME = 16;

	/** Passwords are allowed to be longer than usernames, but not unbounded. */
	public static final int MAX_PASSWORD = 64;

	/** First, middle, last, and preferred names. */
	public static final int MAX_NAME = 50;

	/** The longest email address permitted by the relevant internet standard. */
	public static final int MAX_EMAIL = 254;

	/** Invitation codes are generated by the application and are short. */
	public static final int MAX_INVITATION = 32;

	/**********
	 * <p> Method: checkLength </p>
	 * 
	 * <p> Description: Checks one input against the absolute ceiling and then against the
	 * limit for this particular kind of field.</p>
	 * 
	 * @param input      the text the user typed; null is treated as empty
	 * @param maxLength  the limit for this kind of field, normally one of the constants above
	 * @param fieldName  the name shown to the user in the error message, for example "Username"
	 * 
	 * @return an empty string when the input is an acceptable length, otherwise a message
	 *         that says which field was too long and what the limit is
	 */
	public static String checkLength(String input, int maxLength, String fieldName) {
		if (input == null)
			return "";

		// The cheap ceiling first, so a huge paste never reaches the per-field logic.
		if (input.length() > ABSOLUTE_MAX)
			return fieldName + " is far too long. The limit is " + maxLength + " characters.";

		if (input.length() > maxLength)
			return fieldName + " must be " + maxLength + " characters or fewer. You entered "
					+ input.length() + ".";

		return "";
	}

	/**********
	 * <p> Method: isEmpty </p>
	 * 
	 * <p> Description: A small helper so that the screens all treat null and blank input
	 * the same way.</p>
	 * 
	 * @param input the text the user typed
	 * 
	 * @return true when there is nothing usable in the input
	 */
	public static boolean isEmpty(String input) {
		return input == null || input.isEmpty();
	}
}
